"""The minimal interface HAN actors (han-exec, han-host, han-verify's reader) need from a client, so they run over any binding:
`han.client.Client` (the generic WebSocket binding) and `han.matrix.client.MatrixClient` (Matrix, content over HTTP read) both satisfy it."""
from __future__ import annotations
from typing import Any, AsyncIterator, Protocol, runtime_checkable

@runtime_checkable
class ClientProtocol(Protocol):
    actor: str
    heads: dict[str, int]                                   # space -> highest seq seen (R-17 `seen`)

    def make_entry(self, kind: str, space: str, body: dict, content: Any = None, refs=(), seen: int | None = None) -> tuple[dict, Any]: ...
    async def connect(self) -> Any: ...
    async def close(self) -> None: ...
    async def append(self, entry: dict, content: Any = None, timeout: float | None = None) -> dict: ...
    def read(self, space: str, after: int = 0, follow: bool = False, state: bool = False, limit: int | None = None,
             known_heads: list | None = None, at: int | None = None, cursor: str | None = None,
             effect: str | None = None) -> AsyncIterator[dict]: ...
    async def read_state(self, space: str, at: int | None = None, effect: str | None = None) -> dict: ...
    async def read_all(self, space: str, after: int = 0, **kw) -> list: ...
    def subscribe(self, space: str, after: int | None = None) -> AsyncIterator[dict]: ...
    async def signal(self, space: str, body: Any) -> None: ...
    async def blob_put(self, data: bytes, type: str = ...) -> dict: ...
    async def blob_get(self, ref: dict, space: str) -> bytes: ...
    async def stream(self, item: dict) -> None: ...
    def watch(self, space: str, session: str) -> AsyncIterator[dict]: ...
