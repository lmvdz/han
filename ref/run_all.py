"""Runs every check shipped with HAN v1 and writes ref/RESULTS.md.
  python ref/run_all.py            all checks (model check takes ~15–25 min)
  python ref/run_all.py --quick    skip the model checker
"""
import datetime, os, subprocess, sys
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PY = sys.executable
CHECKS = [
    ("TypeScript strict check of han.ts", ["npx", "-y", "-p", "typescript@5.8.3", "tsc", "-p", os.path.join(ROOT, "tsconfig.json")]),
    ("Three-way consistency (architecture.md §5 · han.ts · ref schema)", [PY, os.path.join(HERE, "check_consistency.py")]),
    ("Conformance vectors against ref/policy.py", [PY, os.path.join(HERE, "run_vectors.py")]),
    ("Policy mutations must be caught by the vectors", [PY, os.path.join(HERE, "mutate_vectors.py")]),
    ("Fold totality fuzz: random histories never crash fold and keep budgets in bounds", [PY, os.path.join(HERE, "fuzz_fold.py")]),
    ("Wire mutations must be caught by the scenarios", [PY, os.path.join(HERE, "mutate_wire.py")]),
    ("Guard model (P-15), depth 5 (~40 s): the invariant holds against the real Policy", [PY, os.path.join(HERE, "model_guard.py")]),
    ("Guard model mutations must each give a counterexample, depth 5", [PY, os.path.join(HERE, "model_guard.py"), "--depth", "5", "--all-mutations"]),
    ("Signed layer (real Ed25519): home pipeline, content validation, mirror verification, proofs, blobs, notices", [PY, os.path.join(HERE, "run_wire.py")]),
    ("Model check: effects, executor, crashes, revocation, abandon, clock offset, delay, rounding, window changes", [PY, os.path.join(HERE, "model_check.py")]),
    ("Model mutations must be caught", [PY, os.path.join(HERE, "model_check.py"), "--all-mutations"]),
]

def main():
    quick = "--quick" in sys.argv
    rows, ok_all = [], True
    for name, cmd, *mode in CHECKS:
        mode = mode[0] if mode else "both"
        if (quick and ("model_check.py" in cmd[1] or mode == "full")) or (not quick and mode == "quick"):
            rows.append((name, "skipped (--quick)" if quick else "skipped (full run uses depth 5)", "")); continue
        r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace",
                           env=dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUTF8="1"), shell=(os.name == "nt" and cmd[0] == "npx"))
        out = "\n".join(l for l in (r.stdout + r.stderr).splitlines() if not l.startswith("npm ")).strip()
        ok = r.returncode == 0
        ok_all &= ok
        rows.append((name, "PASS" if ok else f"FAIL (exit {r.returncode})", out.splitlines()[-1] if out else "(no output; exit 0)"))
        print(f"{'PASS' if ok else 'FAIL'}  {name}\n      {rows[-1][2]}")
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8") as fh:
        fh.write(f"# Check results\n\nGenerated by `python ref/run_all.py{' --quick' if quick else ''}` at "
                 f"{datetime.datetime.now().strftime('%Y-%m-%d %H:%M')} (Python {sys.version.split()[0]}).\n\n"
                 "| Check | Result | Last line of output |\n|---|---|---|\n")
        for n, res, last in rows: fh.write(f"| {n} | {res} | {last.replace('|', '/')} |\n")
    return 0 if ok_all else 1

if __name__ == "__main__":
    sys.exit(main())
